// content/features/sample-duplicate.js
//
// "Duplicate sample" on a molecule's Samples tab: a fourth icon next to
// CDD's Deplete / Edit / New event icons of every sample. It opens CDD's own
// "Create a New Sample" dialog filled in like the sample it sits on, so the
// only thing left to do is pick a location and Save. Nothing is saved by us —
// the dialog is CDD's, Save is the user's click (and the multi-position
// Batch Create bar works in it as usual: several positions → several copies).
//
// What is copied:
//   Batch, Units, Initial Amount (= the parent's CURRENT amount) and every
//   sample field the dialog shows, matched by field name.
// What is not:
//   Sample ID (autogenerated), Barcode (unique per sample), the location
//   (that is the point), and the event fields (Comment…) — those describe
//   the creation event, not the sample.
//
// The sample's data come fresh from inventory_samples.json at the click (the
// current amount moves with every debit); the header's first line is the
// sample's full name, which is how a header is matched to its JSON record.
//
// Page DOM (CDD, verified 2026-09-23):
//   .sticky-header-container .sticky-header        one per sample; innerText
//                                                  starts with the sample name
//   … div.right > a.sample-icon-button             Deplete / Edit / New event
//   a.editableData-editLink "Create a new sample"
//   dialog: [id="sample.batch_id"]                 MUI Select, option data-value = batch id
//           input[name=".initialValue"]            number
//           input[id="sample.units"]               MUI Autocomplete
//           [name="sample.fields.<id>"]            text/number input, or a
//                                                  MUI Select (div[role=combobox] with that id)

import { mouseClick } from "../utils/dom.js";

const LOG_PREFIX = "[CDD stoich plugin]";
const STYLE_ID = "cdd-sample-duplicate-style";
const BUTTON_CLASS = "cdd-sample-duplicate";
const NOTE_CLASS = "cdd-sample-duplicate-note";
const MOLECULE_PATH = /^\/vaults\/(\d+)\/molecules\/(\d+)/;

// Never copied, whatever the vault calls them otherwise.
const SKIPPED_FIELDS = new Set(["sample id", "barcode"]);

const POLL_MS = 100;
const POLL_ATTEMPTS = 50;

let started = false;
let running = false;
let scheduled = false;

function wait(ms) {
    return new Promise((resolve) => setTimeout(resolve, ms));
}

async function waitFor(probe, attempts = POLL_ATTEMPTS) {
    for (let i = 0; i < attempts; i += 1) {
        const result = probe();
        if (result) return result;
        await wait(POLL_MS);
    }
    return null;
}

// React tracks an input's value on the node itself; go through the prototype
// setter so it sees a real edit.
function setNativeValue(element, value) {
    const prototype = element instanceof HTMLTextAreaElement
        ? window.HTMLTextAreaElement.prototype
        : window.HTMLInputElement.prototype;
    const setter = Object.getOwnPropertyDescriptor(prototype, "value")?.set;
    if (setter) setter.call(element, value);
    else element.value = value;
    element.dispatchEvent(new Event("input", { bubbles: true }));
    element.dispatchEvent(new Event("change", { bubbles: true }));
}

// "*Concentration Unit *" (label, with MUI's required mark) and
// "*Concentration Unit" (JSON key) are the same field.
function fieldKey(name) {
    return String(name ?? "")
        .replace(/\s*\*\s*$/, "")
        .replace(/^\s*\*\s*/, "")
        .replace(/\s+/g, " ")
        .trim()
        .toLowerCase();
}

function norm(value) {
    return String(value ?? "").replace(/\s+/g, " ").trim().toLowerCase();
}

/* ------------------------------------------------------------------ *
 * Data
 * ------------------------------------------------------------------ */

async function fetchSample(vaultId, moleculeId, sampleName) {
    const url = `/vaults/${vaultId}/molecules/${moleculeId}/inventory_samples.json?include_depleted=true`;
    const res = await fetch(url, {
        credentials: "include",
        headers: { Accept: "application/json", "X-Requested-With": "XMLHttpRequest" },
    });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const json = await res.json();
    return (json?.inventory_samples || []).find((s) => String(s.name || "").trim() === sampleName) || null;
}

/* ------------------------------------------------------------------ *
 * Dialog filling
 * ------------------------------------------------------------------ */

function findCreateDialog() {
    return Array.from(document.querySelectorAll('[role="dialog"]'))
        .find((d) => d.querySelector('[id="sample.batch_id"]') && /Create a New Sample/i.test(d.textContent || ""))
        || null;
}

function openListboxOptions() {
    const listbox = Array.from(document.querySelectorAll('[role="listbox"]')).pop();
    return listbox ? Array.from(listbox.querySelectorAll('[role="option"]')) : null;
}

async function closeListbox() {
    document.activeElement?.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true }));
    await waitFor(() => !document.querySelector('[role="listbox"]'), 10);
}

// MUI Select: mousedown opens the menu; take the option by value or label.
async function chooseSelect(combobox, match) {
    combobox.dispatchEvent(new MouseEvent("mousedown", { bubbles: true, cancelable: true, button: 0 }));
    const option = await waitFor(() => {
        const options = openListboxOptions();
        return options?.length ? options.find(match) || "none" : null;
    }, 20);
    if (!option || option === "none") {
        await closeListbox();
        return false;
    }
    mouseClick(option);
    await waitFor(() => !document.querySelector('[role="listbox"]'), 10);
    return true;
}

// MUI Autocomplete: type the value, click the option that says exactly that.
async function chooseAutocomplete(input, value) {
    input.focus();
    input.dispatchEvent(new MouseEvent("mousedown", { bubbles: true, button: 0 }));
    const prototype = window.HTMLInputElement.prototype;
    Object.getOwnPropertyDescriptor(prototype, "value").set.call(input, value);
    input.dispatchEvent(new Event("input", { bubbles: true }));
    const option = await waitFor(() => {
        const options = openListboxOptions();
        return options?.length ? options.find((o) => (o.textContent || "").trim() === value) || "none" : null;
    }, 20);
    if (!option || option === "none") {
        await closeListbox();
        return false;
    }
    mouseClick(option);
    await waitFor(() => !document.querySelector('[role="listbox"]'), 10);
    return true;
}

function labelOf(dialog, name) {
    const node = dialog.querySelector(`[name="${CSS.escape(name)}"]`);
    return node?.closest(".MuiFormControl-root")?.querySelector("label")?.textContent || "";
}

// → string[] of what could not be filled (empty = everything landed)
async function fillDialog(dialog, sample) {
    const missed = [];

    const batch = dialog.querySelector('[id="sample.batch_id"]');
    const batchOk = batch && await chooseSelect(batch, (o) => o.getAttribute("data-value") === String(sample.batch_id));
    if (!batchOk) missed.push(`Batch ${sample.batch_name || ""}`.trim());

    const amount = dialog.querySelector('input[name=".initialValue"]');
    if (amount && sample.current_amount != null) setNativeValue(amount, String(sample.current_amount));
    else missed.push("Initial Amount");

    const units = dialog.querySelector('input[id="sample.units"]');
    if (sample.units && !(units && await chooseAutocomplete(units, String(sample.units)))) {
        missed.push(`Units ${sample.units}`);
    }

    const values = new Map(
        Object.entries(sample.fields || {}).map(([name, value]) => [fieldKey(name), value])
    );

    const names = new Set(
        Array.from(dialog.querySelectorAll('[name^="sample.fields."]')).map((n) => n.getAttribute("name"))
    );
    for (const name of names) {
        const label = labelOf(dialog, name);
        const key = fieldKey(label);
        if (!key || SKIPPED_FIELDS.has(key) || !values.has(key)) continue;

        const value = values.get(key);
        if (value == null || value === "") continue;
        const text = typeof value === "object" ? String(value.value ?? value.name ?? "") : String(value);
        if (!text) continue;

        const combobox = dialog.querySelector(`[role="combobox"][id="${CSS.escape(name)}"]`);
        const input = dialog.querySelector(`input[name="${CSS.escape(name)}"]:not(.MuiSelect-nativeInput), textarea[name="${CSS.escape(name)}"]`);
        let ok = false;
        if (combobox && combobox.tagName !== "INPUT") {
            ok = await chooseSelect(combobox, (o) => norm(o.textContent) === norm(text)
                || o.getAttribute("data-value") === text);
        } else if (input && !input.disabled && !input.readOnly) {
            setNativeValue(input, text);
            ok = true;
        }
        if (!ok) missed.push(label.replace(/\s*\*\s*$/, "").trim());
    }

    return missed;
}

function showNote(dialog, sample, missed) {
    dialog.querySelector(`.${NOTE_CLASS}`)?.remove();
    const note = document.createElement("div");
    note.className = NOTE_CLASS;
    note.textContent = `Copy of ${sample.name} — pick a location and Save.`;
    if (missed.length) {
        const warn = document.createElement("div");
        warn.className = `${NOTE_CLASS}__warn`;
        warn.textContent = `Not filled: ${missed.join(", ")}`;
        note.appendChild(warn);
    }
    const title = Array.from(dialog.querySelectorAll("h1,h2,h3,.MuiDialogTitle-root"))
        .find((h) => /Create a New Sample/i.test(h.textContent || ""));
    if (title) title.after(note);
    else dialog.querySelector('[id="sample.batch_id"]')?.closest("form, .MuiDialogContent-root")?.prepend(note);

    const pick = Array.from(dialog.querySelectorAll("button"))
        .find((b) => /Pick Location/i.test(b.textContent || ""));
    pick?.classList.add(`${BUTTON_CLASS}__target`);
}

async function duplicate(header, button) {
    if (running) return;
    const match = location.pathname.match(MOLECULE_PATH);
    const sampleName = (header.innerText || "").split("\n")[0].trim();
    if (!match || !sampleName) return;

    running = true;
    button.classList.add(`${BUTTON_CLASS}--busy`);
    try {
        const sample = await fetchSample(match[1], match[2], sampleName);
        if (!sample) throw new Error(`sample ${sampleName} not found`);

        const link = Array.from(document.querySelectorAll("a.editableData-editLink, a"))
            .find((a) => (a.textContent || "").trim() === "Create a new sample");
        if (!link) throw new Error('"Create a new sample" link not found');
        link.click();

        const dialog = await waitFor(findCreateDialog);
        if (!dialog) throw new Error("Create a New Sample dialog did not open");
        // The dialog renders its options a beat after it appears.
        await wait(150);

        const missed = await fillDialog(dialog, sample);
        showNote(dialog, sample, missed);
    } catch (error) {
        console.warn(LOG_PREFIX, "duplicate sample:", error);
        button.title = `Duplicate failed: ${error.message}`;
    } finally {
        running = false;
        button.classList.remove(`${BUTTON_CLASS}--busy`);
    }
}

/* ------------------------------------------------------------------ *
 * Buttons
 * ------------------------------------------------------------------ */

const ICON = '<svg viewBox="0 0 24 24" width="16" height="16" aria-hidden="true">'
    + '<path fill="currentColor" d="M16 1H4a2 2 0 0 0-2 2v14h2V3h12V1zm3 4H8a2 2 0 0 0-2 2v14a2 2 0 0 0 2 2h11a2 2 0 0 0 2-2V7a2 2 0 0 0-2-2zm0 16H8V7h11v14z"/>'
    + "</svg>";

function addButtons() {
    scheduled = false;
    if (!MOLECULE_PATH.test(location.pathname)) return;

    for (const header of document.querySelectorAll(".sticky-header-container .sticky-header")) {
        const edit = header.querySelector('a.sample-icon-button[aria-label="Edit sample"]');
        const icons = edit?.parentElement;
        if (!icons || icons.querySelector(`.${BUTTON_CLASS}`)) continue;

        const button = document.createElement("a");
        button.className = `${BUTTON_CLASS} sample-icon-button`;
        button.setAttribute("role", "button");
        button.setAttribute("aria-label", "Duplicate sample");
        button.title = "Duplicate sample — same batch, amount and fields; you pick the location";
        button.innerHTML = ICON;
        button.addEventListener("click", (event) => {
            event.preventDefault();
            event.stopPropagation();
            duplicate(header, button);
        });
        icons.insertBefore(button, edit.nextSibling);
    }
}

function schedule() {
    if (scheduled) return;
    scheduled = true;
    requestAnimationFrame(addButtons);
}

function ensureStyle() {
    if (document.getElementById(STYLE_ID)) return;
    const style = document.createElement("style");
    style.id = STYLE_ID;
    style.textContent = `
        .${BUTTON_CLASS} { display: inline-flex; align-items: center; justify-content: center;
            width: 24px; height: 24px; vertical-align: middle; box-sizing: border-box;
            color: #1976d2; cursor: pointer; border-radius: 4px; }
        .${BUTTON_CLASS}:hover { background: rgba(25, 118, 210, 0.08); }
        .${BUTTON_CLASS}--busy { opacity: 0.4; pointer-events: none; }
        .${NOTE_CLASS} { margin: 8px 16px 0; padding: 6px 10px; border-radius: 4px;
            background: #e8f1fb; color: #1a3d63; font-size: 12px; }
        .${NOTE_CLASS}__warn { margin-top: 2px; color: #a4262c; }
        .${BUTTON_CLASS}__target { box-shadow: 0 0 0 2px #1976d2; }
    `;
    document.head.appendChild(style);
}

export function initSampleDuplicate() {
    if (started) return;
    started = true;
    ensureStyle();
    new MutationObserver(schedule).observe(document.documentElement, { childList: true, subtree: true });
    schedule();
}
